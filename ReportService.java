package com.bbms.service;

import com.bbms.model.BloodInventory;
import com.bbms.model.BloodIssue;
import com.bbms.model.Donation;
import com.bbms.model.Donor;

import java.io.File;
import java.io.FileWriter;
import java.io.IOException;
import java.text.SimpleDateFormat;
import java.util.Date;
import java.util.List;

/**
 * Service: ReportService
 * 
 * Generates formatted operational reports for the Administrator:
 * - Blood Stock Summary
 * - Registered Donors Directory
 * - Donation Audit Trail
 * - Blood Issue Audit Trail
 * - Comprehensive Executive Report
 */
public class ReportService {

    private final InventoryService inventoryService;
    private final DonorService donorService;
    private final AuthService authService;

    public ReportService() {
        this.inventoryService = new InventoryService();
        this.donorService = new DonorService();
        this.authService = AuthService.getInstance();
    }

    /**
     * Generates a comprehensive plain-text executive report.
     */
    public String generateExecutiveReport() {
        if (!authService.isLoggedIn()) {
            return "ACCESS DENIED: Please log in as Administrator to view reports.";
        }

        StringBuilder sb = new StringBuilder();
        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd HH:mm:ss");
        String timestamp = sdf.format(new Date());

        sb.append("========================================================================================\n");
        sb.append("                          BLOOD BANK MANAGEMENT SYSTEM                                  \n");
        sb.append("                          EXECUTIVE ADMINISTRATIVE REPORT                               \n");
        sb.append("========================================================================================\n");
        sb.append("Generated On: ").append(timestamp).append("\n");
        sb.append("Generated By: ").append(authService.getCurrentAdmin().getUsername())
          .append(" (").append(authService.getCurrentAdmin().getRole()).append(")\n\n");

        // 1. KPI Summary
        sb.append("----------------------------------------------------------------------------------------\n");
        sb.append("1. EXECUTIVE SUMMARY & KEY PERFORMANCE METRICS\n");
        sb.append("----------------------------------------------------------------------------------------\n");
        sb.append(String.format("Total Registered Donors    : %d\n", donorService.getTotalDonorsCount()));
        sb.append(String.format("Total Blood Units in Stock : %d units\n", inventoryService.getTotalUnitsAvailable()));
        sb.append(String.format("Total Donations Recorded   : %d events (%d units)\n", 
                inventoryService.getTotalDonationsCount(), inventoryService.getTotalUnitsDonated()));
        sb.append(String.format("Total Blood Issues Recorded: %d events (%d units)\n", 
                inventoryService.getTotalIssuesCount(), inventoryService.getTotalUnitsIssued()));
        sb.append("\n");

        // 2. Inventory Status
        sb.append("----------------------------------------------------------------------------------------\n");
        sb.append("2. LIVE BLOOD INVENTORY BY BLOOD GROUP\n");
        sb.append("----------------------------------------------------------------------------------------\n");
        sb.append(String.format("%-15s | %-15s | %-20s\n", "Blood Group", "Units in Stock", "Status"));
        sb.append("----------------------------------------------------------------------------------------\n");
        List<BloodInventory> invList = inventoryService.getAllInventory();
        for (BloodInventory inv : invList) {
            sb.append(String.format("%-15s | %-15d | %-20s\n", 
                    inv.getBloodGroup(), inv.getQuantity(), inv.getStockStatus()));
        }
        sb.append("\n");

        // 3. Registered Donors
        sb.append("----------------------------------------------------------------------------------------\n");
        sb.append("3. REGISTERED DONORS DIRECTORY (CONFIDENTIAL)\n");
        sb.append("----------------------------------------------------------------------------------------\n");
        sb.append(String.format("%-8s | %-25s | %-12s | %-18s\n", "Donor ID", "Full Name", "Blood Group", "Contact"));
        sb.append("----------------------------------------------------------------------------------------\n");
        List<Donor> donors = donorService.getAllDonors();
        if (donors.isEmpty()) {
            sb.append("No donors currently registered.\n");
        } else {
            for (Donor d : donors) {
                sb.append(String.format("%-8d | %-25s | %-12s | %-18s\n",
                        d.getId(), d.getName(), d.getBloodGroup(), d.getContact()));
            }
        }
        sb.append("\n");

        // 4. Recent Donations
        sb.append("----------------------------------------------------------------------------------------\n");
        sb.append("4. RECENT BLOOD DONATIONS LOG\n");
        sb.append("----------------------------------------------------------------------------------------\n");
        sb.append(String.format("%-12s | %-8s | %-22s | %-12s | %-8s\n", "Donation ID", "Donor ID", "Donor Name", "Date", "Units"));
        sb.append("----------------------------------------------------------------------------------------\n");
        List<Donation> donations = inventoryService.getAllDonations();
        if (donations.isEmpty()) {
            sb.append("No donation records found.\n");
        } else {
            for (Donation don : donations) {
                sb.append(String.format("%-12d | %-8d | %-22s | %-12s | %-8d\n",
                        don.getDonationID(), don.getDonorID(),
                        (don.getDonorName() != null ? don.getDonorName() : "Unknown"),
                        don.getDate().toString(), don.getQuantity()));
            }
        }
        sb.append("\n");

        // 5. Recent Issues
        sb.append("----------------------------------------------------------------------------------------\n");
        sb.append("5. RECENT BLOOD ISSUES LOG\n");
        sb.append("----------------------------------------------------------------------------------------\n");
        sb.append(String.format("%-10s | %-12s | %-8s | %-12s | %-25s\n", "Issue ID", "Blood Group", "Units", "Date", "Recipient / Hospital"));
        sb.append("----------------------------------------------------------------------------------------\n");
        List<BloodIssue> issues = inventoryService.getAllIssues();
        if (issues.isEmpty()) {
            sb.append("No issue records found.\n");
        } else {
            for (BloodIssue iss : issues) {
                sb.append(String.format("%-10d | %-12s | %-8d | %-12s | %-25s\n",
                        iss.getIssueID(), iss.getBloodGroup(), iss.getQuantity(),
                        iss.getDate().toString(),
                        (iss.getRecipientInfo() != null ? iss.getRecipientInfo() : "N/A")));
            }
        }
        sb.append("\n");
        sb.append("========================================================================================\n");
        sb.append("                                END OF OFFICIAL REPORT                                  \n");
        sb.append("========================================================================================\n");

        return sb.toString();
    }

    /**
     * Exports the report to a specified local text file.
     */
    public boolean exportReportToFile(File targetFile) {
        String reportText = generateExecutiveReport();
        try (FileWriter writer = new FileWriter(targetFile)) {
            writer.write(reportText);
            return true;
        } catch (IOException e) {
            System.err.println("Error saving report: " + e.getMessage());
            return false;
        }
    }
}
